#!/usr/bin/env python3
"""Regenerate words.js from tools/data.txt and tools/upgrades.txt.

data.txt format:
  # <priority>|<title>|<farsi title>|<description>
  ## <section>|<farsi section>|<skills: R W S L>|<icon>
  <word>|<part of speech>|<farsi meaning>|<example sentence>|<level 1-3>
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent
priorities, sections, words = [], [], []
pr = sec = None
seen = set()

for raw in (root / "data.txt").read_text(encoding="utf-8").splitlines():
    line = raw.strip()
    if not line:
        continue
    if line.startswith("## "):
        title, fa, skills, icon = line[3:].split("|")
        sec = len(sections)
        sections.append({"id": sec, "priority": pr, "title": title, "fa": fa, "skills": list(skills), "icon": icon})
    elif line.startswith("# "):
        num, title, fa, desc = line[2:].split("|")
        pr = int(num)
        priorities.append({"id": pr, "title": title, "fa": fa, "desc": desc})
    else:
        parts = line.split("|")
        assert len(parts) == 5 and all(p.strip() for p in parts), f"bad line: {line}"
        w, pos, fa, ex, lvl = parts
        assert lvl in "123", f"bad level: {line}"
        assert w.lower() not in seen, f"duplicate: {w}"
        seen.add(w.lower())
        words.append({"id": len(words), "w": w, "pos": pos, "fa": fa, "ex": ex,
                      "p": pr, "s": sec, "l": int(lvl)})

upgrades = [l.split("|") for l in (root / "upgrades.txt").read_text(encoding="utf-8").splitlines() if l.strip()]

assert len(words) >= 300, len(words)
out = root.parent / "words.js"
out.write_text(
    "// Generated by tools/build_words.py. Edit tools/data.txt instead.\n"
    f"const PRIORITIES = {json.dumps(priorities, ensure_ascii=False)};\n"
    f"const SECTIONS = {json.dumps(sections, ensure_ascii=False)};\n"
    f"const UPGRADES = {json.dumps(upgrades, ensure_ascii=False)};\n"
    f"const WORDS = {json.dumps(words, ensure_ascii=False, indent=0)};\n",
    encoding="utf-8",
)
print(f"{len(words)} words, {len(sections)} sections -> {out}")
